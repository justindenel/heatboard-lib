/** Name of a theme token, without the `--hb-` prefix. */
export type ThemeTokenName = (typeof THEME_TOKEN_NAMES)[number];

/** CSS values keyed by token name; an absent token keeps the value of the base theme. */
export type ThemeTokens = Partial<Record<ThemeTokenName, string>>;

export interface HeatboardTheme {
	name: string;
	light: ThemeTokens;
	dark: ThemeTokens;
}

export type ColorScheme = "light" | "dark";

/** `system` follows `prefers-color-scheme` and tracks its changes. */
export type ColorSchemeSetting = ColorScheme | "system";
