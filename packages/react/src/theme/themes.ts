/** Builds a theme; unset tokens come from `extends` (`themes.classic` by default). */
export function defineTheme(definition: ThemeDefinition = {}): HeatboardTheme {
	const base = definition.extends ?? classic;
	return {
		name: definition.name ?? "custom",
		light: { ...base.light, ...definition.light },
		dark: { ...base.dark, ...definition.dark },
	};
}

